  assert.equal(await page.locator("#evaluation-preview").evaluate(n=>n===document.activeElement),true);
  const preview=await page.locator("#evaluation-preview h3").boundingBox(), dialogRect=await page.locator("dialog").boundingBox();
  assert.ok(preview.y>=dialogRect.y && preview.y<dialogRect.y+dialogRect.height);
  await page.getByRole("button",{name:"Close dialog",exact:true}).click();
  await page.getByRole("button",{name:"Blacklist song",exact:true}).click();
  await nav("blacklist");
  await page.getByRole("heading",{name:song.title,exact:true,level:2}).waitFor();
  assert.ok(await page.locator(".primary-evaluation").count());
  assert.ok(await page.getByRole("button",{name:"Manage recording links",exact:true,includeHidden:true}).count());
  assert.equal(await page.getByRole("button",{name:"Add to plan ›",exact:true}).count(),0);
  await nav("discover");await page.getByLabel("Search songs").fill(song.title);
  assert.equal(await page.locator(`.song-card[data-id="${song.id}"]`).count(),0);
  assert.equal(await page.locator(`.closest-matches [data-id="${song.id}"]`).count(),0);
  await nav("profile");
  await reveal(page,"button",{name:"Add Corporate participation",exact:true});
