  const last=page.locator(".song-card").last(), title=await last.locator("h3").textContent();
  await last.scrollIntoViewIfNeeded(); const top=await page.locator(".song-list").evaluate(n=>n.scrollTop);
  await last.click();
  assert.equal(await page.locator(".detail-panel h2").textContent(),title);
  assert.equal(await page.locator(".song-list").evaluate(n=>n.scrollTop),top);
  const rect=await page.locator(".detail-panel h2").boundingBox();assert.ok(rect.y>=0 && rect.y<1000,"Chosen heading stays visible");
  await page.getByLabel("Song page",{exact:true}).fill("2");
  await page.getByLabel("Song page",{exact:true}).press("Enter");
  assert.equal(await page.getByLabel("Song page",{exact:true}).inputValue(),"2");
  await nav("discover");
  const song=(await state()).songs[0];
  await reveal(page,"button",{name:"Generate AI evaluation",exact:true});
  await page.getByRole("button",{name:"Generate AI evaluation",exact:true}).click();
