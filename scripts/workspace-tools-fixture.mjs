import assert from "node:assert/strict";
import { reveal } from "./disclosure.mjs";

// Called inside the signed-in provider fixture, before its profile/account checks.
export async function checkWorkspaceToolsFlows(page) {
  const nav = async (name) => page.locator("nav").getByRole("button", { name, exact: true }).click();
  const click = async (name) => {
    await reveal(page, "button", { name, exact: true });
    await page.getByRole("button", { name, exact: true }).click();
  };
  const workspace = () => page.evaluate(() => {
    const session = JSON.parse(localStorage.getItem("faithful-repertoire-session"));
    return JSON.parse(localStorage.getItem("faithful-repertoire-user:" + session.session.user.id));
  });
  await nav("Song index");
  await page.getByLabel("Search across all indexed fields", { exact: true }).fill("Amazing Grace");
  await click("Search index");
  await reveal(page, "combobox", { name: "Index field", exact: true });
  const filter = page.locator("#index-filter-form");
  await filter.getByLabel("Index field").selectOption("tempo");
  await filter.getByLabel("Index match").selectOption("missing");
  await filter.getByRole("button", { name: "Add filter", exact: true }).click();
  await page.getByLabel("Additional column").selectOption("interiorJust");
  await page.getByLabel("Index sort").selectOption("substance");
  await page.getByLabel("Index order").selectOption("desc");
  await click("Save current view");
  await page.getByLabel("View name").fill("Lyric review");
  await click("Save view");
  const saved = (await workspace()).indexViews[0];
  assert.equal(saved.rules[0].op, "missing");
  assert.equal(saved.column, "interiorJust");
  await click("Reset index");
  await reveal(page, "combobox", { name: "Saved index view", exact: true });
  await page.getByLabel("Saved index view").selectOption(saved.id);
  await click("Apply view");
  assert.equal(await page.getByLabel("Search across all indexed fields").inputValue(), "Amazing Grace");
  assert.equal(await page.getByLabel("Index order").inputValue(), "desc");
  assert.match(await page.locator(".index-rules").textContent(), /Tempo/);
  await click("Rename selected view");
  await page.getByLabel("View name").fill("Missing tempo, lyric review");
  await click("Save view");
  assert.equal((await workspace()).indexViews[0].name, "Missing tempo, lyric review");
  await page.reload();
  await page.getByRole("button", { name: "My account", exact: true }).waitFor();
  await nav("Song index");
  await reveal(page, "combobox", { name: "Saved index view", exact: true });
  await page.getByLabel("Saved index view").selectOption(saved.id);
  await click("Apply view");
  assert.equal(await page.getByLabel("Additional column").inputValue(), "interiorJust");
  assert.equal(await page.getByLabel("Index sort").inputValue(), "substance");

  await nav("Plans");
  await click("+ New plan");
  await page.getByLabel("Plan name").fill("Evening service");
  await page.getByLabel("Date", { exact: true }).fill("2026-10-11");
  await page.getByLabel("Plan status").selectOption("completed");
  await click("Create plan");
  await click("Add item");
  await page.getByLabel("Item title").fill("Scripture reading");
  await page.getByLabel("Notes").fill("Psalm 46:1–3");
  await click("Save item");
  await nav("Discover songs");
  await click("Add to library");
  await page.locator('#save-song-form input[value="personal"]').check();
  await page.locator("#save-song-form button.primary").click();
  await click("Add to plan ›");
  await page.getByLabel("Key", { exact: true }).fill("D");
  await click("Add to plan");
  await click("Save as template");
  await page.getByLabel("Template name").fill("Evening order");
  await click("Save template");
  const before = await workspace();
  assert.equal(before.plans.length, 1);
  assert.equal(before.planTemplates.length, 1);
  assert.equal(before.planTemplates[0].date, "");
  assert.equal(before.planTemplates[0].status, "draft");
  await click("Plan templates");
  await click("Use template");
  await page.getByLabel("Plan name").fill("Next evening service");
  await page.getByLabel("Date", { exact: true }).fill("2026-10-18");
  await click("Create draft");
  const after = await workspace();
  assert.equal(after.plans.length, 2);
  assert.equal(after.plans[1].status, "draft");
  assert.notEqual(after.plans[1].items[0].id, after.planTemplates[0].items[0].id);
  assert.equal(after.plans[1].items[1].key, "D");
  await click("Save as template");
  await page.getByLabel("Template name").fill("Order without songs");
  await page.getByLabel("Keep selected songs").uncheck();
  await click("Save template");
  assert.equal((await workspace()).planTemplates[1].items[1].type, "other");

  await nav("Song index");
  const snapshot = JSON.stringify(await workspace());
  await click("AI criteria search · optional");
  await page.getByLabel("Your criterion").fill("Songs with concrete statements about God's faithfulness.");
  await click("Prepare ChatGPT search");
  const request = await page.getByLabel("ChatGPT search request").inputValue();
  assert.match(request, /Library ID: "personal"/);
  assert.match(request, /Do not suggest worship songs/);
  assert.equal(JSON.stringify(await workspace()), snapshot, "Preparing a ChatGPT request must not mutate records");
  await click("Close");
  await page.setViewportSize({ width: 390, height: 844 });
  await click("Apply view");
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await nav("Plans");
  await click("Plan templates");
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "/tmp/faithful-templates-mobile.png", fullPage: true });
  await click("Close templates");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await nav("Song index");
  if (await page.locator(".index-filter-panel[open]").count())
    await page.locator(".index-filter-panel > summary").click();
  await page.screenshot({ path: "/tmp/faithful-saved-views.png", fullPage: true });
  await nav("Discover songs");
  console.log("PASS: signed-in saved views, template snapshots and independent drafts, ChatGPT criteria prompt without API requests or workspace mutations, reload and mobile layout.");
}
