import test from "node:test";
import assert from "node:assert/strict";
import { evaluationPrompt, parseEvaluation, applyEvaluation } from "../public/evaluation.js";
import { defaultProfile } from "../public/core.js";
import { catalogSongs, syncCatalog } from "../public/catalog.js";
import { reviewForDisplay } from "../public/profile.js";
import { validateWorkspace } from "../public/backup.js";
const song = () => structuredClone(catalogSongs[0]);
const result = (record, mode = "full") => ({ schema: "faithful-evaluation-v1", songId: record.id, aiMode: mode, review: { scores: { accuracy: mode === "full" ? 9 : null, substance: null, language: null, time: null }, summary: "A draft based on supplied text.", claims: [], concerns: [], uses: [], scriptures: [], themes: [], language: "Complete sentences.", time: "", concern: "none", sources: [] } });
test("evaluation requests honor account preferences and do not include private notes or lyrics", () => {
  const s = song(); s.review.notes = "PRIVATE NOTE"; s.lyrics = "PRIVATE LYRICS";
  const full = evaluationPrompt(s, { ...defaultProfile, aiMode: "full", principles: "CHURCH CONVICTIONS" });
  assert.match(full, /CHURCH CONVICTIONS/); assert.match(full, /faithful-evaluation-v1/);
  assert.ok(!full.includes("PRIVATE NOTE") && !full.includes("PRIVATE LYRICS"));
  const limited = evaluationPrompt(s, { ...defaultProfile, aiMode: "limited", principles: "CHURCH CONVICTIONS" });
  assert.ok(!limited.includes("CHURCH CONVICTIONS")); assert.match(limited, /All scores must be null/);
  assert.throws(() => evaluationPrompt(s, { aiMode: "manual" }), /disabled/);
});
test("JSON import binds the record and mode, rejects unsafe or oversized data and vague Scripture", () => {
  const s = song(), value = result(s), parse = () => parseEvaluation(JSON.stringify(value), s.id, "full");
  assert.deepEqual(parse(), value);
  assert.throws(() => parseEvaluation(JSON.stringify(value), "other", "full"), /different song/);
  assert.throws(() => parseEvaluation(JSON.stringify(value), s.id, "limited"), /different song/);
  value.review.scores.accuracy = 11; assert.throws(parse, /score/);
  value.review.scores.accuracy = 9;
  value.review.sources = [{ url: "javascript:alert(1)", label: "Bad" }]; assert.throws(parse, /HTTP/);
  value.review.sources = [{ url: "https://name:password@example.com", label: "Bad" }]; assert.throws(parse, /HTTP/);
  value.review.sources = []; value.review.scriptures = ["Psalms — praise"]; assert.throws(parse, /chapter and verse/);
  value.review.scriptures = ["John 3:16 — thematic connection"]; assert.throws(parse, /chapter and verse/);
  value.review.scriptures = ["John 3:16 — clear allusion: God's gift of his Son."]; assert.equal(parse().review.scriptures.length, 1);
  value.review.notes = "Overwrite"; assert.throws(parse, /unsupported fields/);
  assert.throws(() => parseEvaluation("x".repeat(65537), s.id, "full"), /64 KB/);
  assert.throws(() => parseEvaluation("no JSON", s.id, "full"), /JSON/);
});
test("applying a full draft keeps a human assessment primary and preserves its approval", () => {
  const s = song(); Object.assign(s.review, { status: "manual", notes: "My note", key: "D", minutes: 3, musical: "Measured octave" });
  s.approval = { status: "approved", notes: "Use these verses", updatedAt: null };
  s.metadata = { themes: ["Human theme"], custom: [{ name: "Difficulty", value: "Medium", type: "text" }] };
  const original = structuredClone(s), value = result(s); value.review.themes = ["AI theme"];
  const next = applyEvaluation(s, value, "full");
  assert.deepEqual(s, original);
  assert.equal(next.review.status, "manual"); assert.deepEqual(next.review, original.review);
  assert.equal(next.aiReview.status, "ai"); assert.equal(next.aiReview.scores.accuracy, 9);
  for (const key of ["notes", "key", "minutes", "musical"]) assert.equal(next.review[key], s.review[key]);
  assert.deepEqual(next.metadata, s.metadata); assert.deepEqual(next.themes, s.themes);
  assert.equal(next.approval.status, "approved"); assert.equal(next.approval.notes, "Use these verses");
  assert.equal(reviewForDisplay(next, "manual").status, "manual");
  const again = applyEvaluation(next, value, "full"); assert.ok(!again.aiReview.previous);
  const state = syncCatalog({ version: 1, profile: defaultProfile, songs: [], libraries: [{ id: "mine", name: "Mine", songIds: [] }], plans: [] });
  state.songs[0] = next;
  assert.equal(validateWorkspace(state).songs[0].review.notes, "My note");
  assert.equal(syncCatalog(state).songs[0].aiReview.model, "ChatGPT evaluation · user-imported");
});
test("limited observations cannot import theological ratings and never replace a review or approval", () => {
  const s = song(); s.approval = { status: "approved", notes: "Approved", updatedAt: null };
  const draft = result(s, "limited"), next = applyEvaluation(s, draft, "limited");
  assert.deepEqual(next.approval, s.approval);
  const base = structuredClone(next.review); delete base.assistance; assert.deepEqual(base, s.review);
  assert.equal(next.review.assistance.summary, draft.review.summary);
  assert.ok(!reviewForDisplay(next, "manual").assistance);
  draft.review.scores.accuracy = 9; assert.throws(() => applyEvaluation(s, draft, "limited"), /Limited assistance/);
  assert.throws(() => applyEvaluation(s, result(s), "manual"), /disabled/);
});
